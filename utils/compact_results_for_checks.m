function results_save = compact_results_for_checks(results)

keepFields = { ...
    'L_min', ...
    'AE_OLS_all', ...
    'AE_MLE_all', ...
    'SE_OLS_all', ...
    'SE_MLE_all', ...
    'AE_OLS_STAT_all', ...
    'AE_MLE_STAT_all', ...
    'SE_OLS_STAT_all', ...
    'SE_MLE_STAT_all', ...
    'AIC_OLS_IS_all', ...
    'AIC_MLE_IS_all', ...
    'OLSLOSS_IS_all', ...
    'eta_OLS_store', ...
    'eta_MLE_store', ...
    'mu_OLS_store', ...
    'alpha_OLS_store', ...
    'realized_all', ...
    'pred_OLS_all', ...
    'pred_MLE_all'};

results_save = struct([]);

for rr = 1:numel(results)
    for ff = 1:numel(keepFields)
        f = keepFields{ff};
        if isfield(results(rr), f)
            results_save(rr).(f) = results(rr).(f);
        end
    end
end